-- ============================================================
-- SMART RECIPE & FOOD DISCOVERY SYSTEM
-- PostgreSQL Relational Schema
-- Database: smart_recipe_db
-- ============================================================

-- ============================================================
-- 1. USERS
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 2. CATEGORIES
-- ============================================================

CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description VARCHAR(255)
);


-- ============================================================
-- 3. CUISINES
-- ============================================================

CREATE TABLE IF NOT EXISTS cuisines (
    cuisine_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description VARCHAR(255)
);


-- ============================================================
-- 4. RECIPE METADATA
--
-- IMPORTANT:
-- Full recipe content is NOT stored here.
-- BaseX remains the master recipe database.
-- ============================================================

CREATE TABLE IF NOT EXISTS recipe_metadata (
    recipe_id VARCHAR(10) PRIMARY KEY,
    category_id INTEGER NOT NULL,
    cuisine_id INTEGER NOT NULL,
    dietary_type VARCHAR(30) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 5. RESTAURANTS
--
-- Spatial location will be added in spatial.sql using PostGIS.
-- ============================================================

CREATE TABLE IF NOT EXISTS restaurants (
    restaurant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(300) NOT NULL,
    phone VARCHAR(30),
    rating NUMERIC(2,1) NOT NULL DEFAULT 0,
    opening_time TIME NOT NULL,
    closing_time TIME NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 6. RESTAURANT DISHES
--
-- recipe_id links relational restaurant information
-- to a recipe whose complete content exists in BaseX.
-- ============================================================

CREATE TABLE IF NOT EXISTS restaurant_dishes (
    restaurant_dish_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL,
    recipe_id VARCHAR(10) NOT NULL,
    dish_name VARCHAR(150) NOT NULL,
    price NUMERIC(10,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_restaurant_recipe
        UNIQUE (restaurant_id, recipe_id)
);


-- ============================================================
-- 7. RATINGS
--
-- Official rating records belong in PostgreSQL.
-- ============================================================

CREATE TABLE IF NOT EXISTS ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recipe_id VARCHAR(10) NOT NULL,
    rating SMALLINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_user_recipe_rating
        UNIQUE (user_id, recipe_id)
);


-- ============================================================
-- 8. REVIEWS
-- ============================================================

CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recipe_id VARCHAR(10) NOT NULL,
    review_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_user_recipe_review
        UNIQUE (user_id, recipe_id)
);


-- ============================================================
-- 9. ACTIVITY EVENTS
--
-- Used for relational analytics.
-- Flexible personalization history remains in MongoDB.
-- ============================================================

CREATE TABLE IF NOT EXISTS activity_events (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    event_type VARCHAR(40) NOT NULL,
    recipe_id VARCHAR(10),
    restaurant_id BIGINT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);